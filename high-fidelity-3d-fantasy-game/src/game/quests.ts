// ---------------------------------------------------------------------------
// THE SIDE QUESTS OF THE ASHVEIL — a data-driven questbook.
//
// Every quest here is meant to feel like a person asking for help, not a
// ledger entry. Different shapes, different voices, different payoffs:
//   cull      — thin the ash-beasts (kill N of a kind)
//   collect   — recover M scavenged tokens from the waste
//   reach     — travel to a waypoint and take the moment
//   lore      — read N lore stones scattered through the world
//   mark      — hunt a named elite: a real fight you can't solo-ignore
//   chain     — a multi-site investigation, each stop read in turn
//   deliverTo — take something to someone who isn't the giver
// Quests bind to the named souls of the settlements (giver fields in this file).
// ---------------------------------------------------------------------------

import { REGIONAL_QUESTS } from "./regionalStories";

export type QuestKind = "cull" | "collect" | "reach" | "lore" | "mark" | "chain" | "deliverTo" | "guardian";

export interface QuestDef {
  id: string;
  /** The job as the giver states it in the offer. */
  name: string;
  /** Village NPC id from npcData.ts who hands it out. */
  giver: string;
  kind: QuestKind;
  /** cull: which enemy family; collect: which token tag; lore: stones to read. */
  tag?: "wretch" | "warden" | string;
  count: number;
  /** Objective line for the tracker/journal. */
  hint: string;
  offer: string[];
  reminder: string[];
  done: string[];
  reward: { runes: number; flasks?: number };
  /** VERB shown in the interaction prompt at a reach spot, e.g. Survey. */
  verb?: string;
  /** Where the reach-quest completes. */
  spot?: [number, number];
  /** The place's name for the banner, e.g. "THE SEISMIC RIDGE". */
  place?: string;
  /** mark — a named elite spawns when the quest starts. */
  mark?: { name: string; kind: "warden" | "wretch"; hp: number; tint: number; scale: number; spot: [number, number] };
  /** chain — a sequence of waypoints, each read in order. */
  steps?: { id: string; verb: string; place: string; spot: [number, number]; text?: string[] }[];
  /** deliverTo — the target villager (different from the giver). */
  deliverTo?: string;
  /** Optional regional stories never gate exploration or boss encounters. */
  requires?: string;
  guardianId?: string;
}

